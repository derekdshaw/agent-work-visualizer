func TestAnalyzeResolutionEntrypointsAndDeterminism(t *testing.T) {
	root := t.TempDir()
	writeFixture(t, root, "pkg/a.py", `
from .b import imported as alias
from . import b as mod

def decorate(fn):
    return fn

@decorate
async def local(value: int = factory()) -> int:
    return helper(value)

class Flow(FlowSpec):
    @step
    def start(self):
        helper()
        helper()
        self.next(self.finish, self.alternate)

    @step
    def finish(self):
        pass

    @step
    def alternate(self):
        pass

class Worker:
    @classmethod
    def build(cls):
        return cls.work()

    def work(self):
        return 1

    def run(self):
        return self.work()

def helper(value=0):
    return value

def outer():
    def nested():
        return helper()
    nested()
    alias()
    mod.target()
    external.unknown()
    values = [helper(x) for x in range(3)]
    match values:
        case []:
            return lambda: helper()
        case _:
            return values

def main():
    Flow()
    return outer()

if __name__ == "__main__":
    raise SystemExit(main())
`)
	writeFixture(t, root, "pkg/b.py", `
def imported():
    return target()

def target():
    return 1
`)
	writeFixture(t, root, "pkg/__init__.py", `
from .b import target

def package_call():
    return target()
`)
	writeFixture(t, root, "tests/test_ignored.py", "def ignored():\n    pass\n")
	writeFixture(t, root, ".agent-env/bin/activate_this.py", "def omitted_environment_function():\n    pass\n")
	writeFixture(t, root, "pkg/generated.py", `
"""Generated fixture with a module docstring."""

# Generated by a fixture; do not edit.
def omitted():
    pass
`)

	first, err := Analyze(root, Options{})
	if err != nil {
		t.Fatal(err)
	}
	second, err := Analyze(root, Options{})
	if err != nil {
		t.Fatal(err)
	}
	firstJSON, err := marshalGraph(first)
	if err != nil {
		t.Fatal(err)
	}
	secondJSON, err := marshalGraph(second)
	if err != nil {
		t.Fatal(err)
	}
	if string(firstJSON) != string(secondJSON) {
		t.Fatal("analysis is not deterministic")
	}
	if first.Stats.Files != 3 {
		t.Fatalf("files = %d, want 3", first.Stats.Files)
	}
	if first.Stats.Definitions != 15 || first.Stats.Calls != 21 {
		t.Fatalf("fidelity stats = %+v, want 15 definitions and 21 calls", first.Stats)
	}
	if findFunction(t, first, "pkg.a.main").EntryKind != "main" {
		t.Fatal("main guard did not mark main as an entrypoint")
	}
	if findFunction(t, first, "pkg.a.Flow.start").EntryKind != "metaflow-step" {
		t.Fatal("@step method was not marked as a Metaflow entrypoint")
	}
	if !strings.Contains(findFunction(t, first, "pkg.a.Flow.start").Source, "self.next(self.finish, self.alternate)") {
		t.Fatal("function source was not captured")
	}

	assertEdge(t, first, "pkg.a.Flow.start", "pkg.a.helper", "call", 2)
	assertEdge(t, first, "pkg.a.Flow.start", "pkg.a.Flow.finish", "transition", 1)
	assertEdge(t, first, "pkg.a.Flow.start", "pkg.a.Flow.alternate", "transition", 1)
	assertEdge(t, first, "pkg.a.Worker.build", "pkg.a.Worker.work", "call", 1)
	assertEdge(t, first, "pkg.a.Worker.run", "pkg.a.Worker.work", "call", 1)
	assertEdge(t, first, "pkg.a.outer", "pkg.a.outer.nested", "call", 1)
	assertEdge(t, first, "pkg.a.outer", "pkg.b.imported", "call", 1)
	assertEdge(t, first, "pkg.a.outer", "pkg.b.target", "call", 1)
	assertEdge(t, first, "pkg.package_call", "pkg.b.target", "call", 1)
	if !slices.ContainsFunc(first.Unresolved, func(call UnresolvedCall) bool {
		return call.Expression == "external.unknown"
	}) {
		t.Fatal("external call was not retained as unresolved")
	}
}

