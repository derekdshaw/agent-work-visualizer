func TestRejectsGoRustAndTypescriptSyntaxErrors(t *testing.T) {
	tests := []struct {
		name     string
		file     string
		contents string
	}{
		{name: "go", file: "broken.go", contents: "package broken\n\nfunc broken( {}\n"},
		{name: "rust", file: "broken.rs", contents: "fn broken( {}\n"},
		{name: "typescript", file: "broken.ts", contents: "function broken( {\n"},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			root := t.TempDir()
			langtest.WriteFixture(t, root, test.file, test.contents)
			_, err := langtest.Analyze(root, analyzer.Options{}, python.New(), golang.New(), java.New(), rust.New(), typescript.New())
			if err == nil {
				t.Fatalf("Analyze accepted malformed %s", test.name)
			}
			matched, matchErr := regexp.MatchString(regexp.QuoteMeta(test.file)+`:\d+:\d+:`, err.Error())
			if matchErr != nil {
				t.Fatal(matchErr)
			}
			if !matched {
				t.Fatalf("error lacks path, line, and column: %v", err)
			}
		})
	}
}

// fakeLanguage records the files it is handed and emits one node per file.
type fakeLanguage struct {
	name       string
	extensions []string
	skipDirs   []string
	received   []string
}

func (f *fakeLanguage) Name() string         { return f.name }
func (f *fakeLanguage) Extensions() []string { return f.extensions }
func (f *fakeLanguage) SkipDirs() []string   { return f.skipDirs }
func (f *fakeLanguage) IsTestFile(relativePath string) bool {
	return filepath.Base(relativePath) == "skip.test"
}

func (f *fakeLanguage) Analyze(root string, files []string) (*callgraph.Graph, error) {
	f.received = files
	graph := &callgraph.Graph{}
	for _, path := range files {
		relative, err := filepath.Rel(root, path)
		if err != nil {
			return nil, err
		}
		graph.Files = append(graph.Files, callgraph.File{Path: filepath.ToSlash(relative), Language: f.name})
		graph.Nodes = append(graph.Nodes, callgraph.Function{ID: f.name + ":" + filepath.ToSlash(relative)})
		graph.Stats.Files++
		graph.Stats.Definitions++
	}
	return graph, nil
}

func TestAnalyzeRoutesFilesByExtensionAndMergesGraphs(t *testing.T) {
	root := t.TempDir()
	langtest.WriteFixture(t, root, "b.one", "")
	langtest.WriteFixture(t, root, "a.one", "")
	langtest.WriteFixture(t, root, "c.two", "")
	langtest.WriteFixture(t, root, "skip.test", "")
	langtest.WriteFixture(t, root, "ignored.txt", "")
	langtest.WriteFixture(t, root, "gen.one", "// Code generated by tool. DO NOT EDIT.\n")
	langtest.WriteFixture(t, root, "deps/inside.one", "")
	langtest.WriteFixture(t, root, ".git/inside.two", "")
	one := &fakeLanguage{name: "one", extensions: []string{".one", ".test"}, skipDirs: []string{"deps"}}
	two := &fakeLanguage{name: "two", extensions: []string{".two"}}

	graph, err := langtest.Analyze(root, analyzer.Options{}, two, one)
	if err != nil {
		t.Fatal(err)
	}
	if !slices.Equal(relativePaths(t, root, one.received), []string{"a.one", "b.one"}) {
		t.Fatalf("language one received %v", one.received)
	}
	if !slices.Equal(relativePaths(t, root, two.received), []string{"c.two"}) {
		t.Fatalf("language two received %v", two.received)
	}
	if graph.Stats.Files != 3 || graph.Stats.Definitions != 3 {
		t.Fatalf("stats = %+v, want 3 files and 3 definitions", graph.Stats)
	}
	var ids []string
	for _, node := range graph.Nodes {
		ids = append(ids, node.ID)
	}
	if !slices.Equal(ids, []string{"one:a.one", "one:b.one", "two:c.two"}) {
		t.Fatalf("merged nodes = %v", ids)
	}

	withTests := &fakeLanguage{name: "one", extensions: []string{".one", ".test"}}
	if _, err := langtest.Analyze(root, analyzer.Options{IncludeTests: true}, withTests); err != nil {
		t.Fatal(err)
	}
	if !slices.Contains(relativePaths(t, root, withTests.received), "skip.test") {
		t.Fatalf("IncludeTests did not include the test file: %v", withTests.received)
	}
}

func TestRegisterRejectsDuplicates(t *testing.T) {
	a := analyzer.New()
	if err := a.Register(&fakeLanguage{name: "one", extensions: []string{".x"}}); err != nil {
		t.Fatal(err)
	}
	if err := a.Register(&fakeLanguage{name: "two", extensions: []string{".y", ".x"}}); err == nil {
		t.Fatal("Register accepted an extension that is already registered")
	}
	if err := a.Register(&fakeLanguage{name: "one", extensions: []string{".z"}}); err == nil {
		t.Fatal("Register accepted a duplicate language name")
	}
}

func relativePaths(t *testing.T, root string, paths []string) []string {
	t.Helper()
	var relative []string
	for _, path := range paths {
		value, err := filepath.Rel(root, path)
		if err != nil {
			t.Fatal(err)
		}
		relative = append(relative, filepath.ToSlash(value))
	}
	return relative
}

func TestOutlineMatchesAnalyzeKeys(t *testing.T) {
	root := t.TempDir()
	langtest.WriteFixture(t, root, "py/app.py", `
class Worker:
    def run(self):
        def nested():
            return 1
        return nested()

def helper():
    return Worker().run()
`)
	langtest.WriteFixture(t, root, "go.mod", "module example.com/demo\n\ngo 1.24\n")
	langtest.WriteFixture(t, root, "gopkg/server.go", `
package gopkg

type Server struct{}

func (s *Server) Start() { helper() }

func helper() {}
`)
	langtest.WriteFixture(t, root, "java/com/example/Service.java", `
package com.example;

public class Service {
    public Service() {}

    public void handle(String value) {
        clean(value);
    }

    private static String clean(String value) {
        return value;
    }
}
`)
	langtest.WriteFixture(t, root, "rust/src/lib.rs", `
mod inner {
    pub fn inside() {}
}

pub struct Worker;

impl Worker {
    pub fn build() {
        inner::inside();
    }
}
`)
	langtest.WriteFixture(t, root, "ts/app.ts", `
export class Worker {
    constructor() {}
    run(): void {}
}

export const local = (): void => {
    new Worker().run();
};
`)
	a := allLanguages(t)
	graph, err := a.Analyze(root, analyzer.Options{})
	if err != nil {
		t.Fatal(err)
	}
	want := make(map[string][]string)
	for _, function := range graph.Nodes {
		want[function.File] = append(want[function.File], activity.Key(function.File, function.QualifiedName))
	}
	if len(want) != 5 {
		t.Fatalf("analysis found callables in %d files, want 5", len(want))
	}
	for file, keys := range want {
		functions, err := a.Outline(root, filepath.Join(root, filepath.FromSlash(file)))
		if err != nil {
			t.Fatalf("outline %s: %v", file, err)
		}
		var got []string
		for _, function := range functions {
			got = append(got, activity.Key(function.File, function.QualifiedName))
		}
		slices.Sort(got)
		slices.Sort(keys)
		if !slices.Equal(got, keys) {
			t.Fatalf("outline keys for %s = %q, want %q", file, got, keys)
		}
	}
}

func TestOutlineSkipsUnsupportedLanguages(t *testing.T) {
	root := t.TempDir()
	langtest.WriteFixture(t, root, "README.md", "# Title\n")
	functions, err := allLanguages(t).Outline(root, filepath.Join(root, "README.md"))
	if err != nil || functions != nil {
		t.Fatalf("Outline = %v, %v, want no callables and no error", functions, err)
	}
}

func TestEmptyGraphListsEncodeAsArrays(t *testing.T) {
	root := t.TempDir()
	langtest.WriteFixture(t, root, "settings.py", "LIMIT = 1\n")
	graph, err := allLanguages(t).Analyze(root, analyzer.Options{})
	if err != nil {
		t.Fatal(err)
	}
	data, err := json.Marshal(graph)
	if err != nil {
		t.Fatal(err)
	}
	for _, field := range []string{`"nodes":[]`, `"edges":[]`, `"unresolved":[]`} {
		if !strings.Contains(string(data), field) {
			t.Errorf("graph JSON lacks %s: %s", field, data)
		}
	}
}

func allLanguages(t *testing.T) *analyzer.Analyzer {
	t.Helper()
	a := analyzer.New()
	for _, language := range []analyzer.Language{python.New(), golang.New(), java.New(), rust.New(), typescript.New()} {
		if err := a.Register(language); err != nil {
			t.Fatal(err)
		}
	}
	return a
}
