func TestAnalyzeResolutionEntrypointsAndDeterminism(t *testing.T) {
	root := t.TempDir()
	langtest.WriteFixture(t, root, "pkg/a.py", `
from .b import imported as alias
from . import b as mod

def decorate(fn):
    return fn

@decorate
async def local(value: int = factory()) -> int:
    return helper(value)

class Flow(FlowSpec):
    @step
    def start(self):
        helper()
        helper()
        self.next(self.finish, self.alternate)

    @step
    def finish(self):
        pass

    @step
    def alternate(self):
        pass

class Worker:
    @classmethod
    def build(cls):
        return cls.work()

    def work(self):
        return 1

    def run(self):
        return self.work()

def helper(value=0):
    return value

def outer():
    def nested():
        return helper()
    nested()
    alias()
    mod.target()
    external.unknown()
    values = [helper(x) for x in range(3)]
    match values:
        case []:
            return lambda: helper()
        case _:
            return values

def main():
    Flow()
    return outer()

if __name__ == "__main__":
    raise SystemExit(main())
`)
	langtest.WriteFixture(t, root, "pkg/b.py", `
def imported():
    return target()

def target():
    return 1
`)
	langtest.WriteFixture(t, root, "pkg/__init__.py", `
from .b import target

def package_call():
    return target()
`)
	langtest.WriteFixture(t, root, "tests/test_ignored.py", "def ignored():\n    pass\n")
	langtest.WriteFixture(t, root, ".agent-env/bin/activate_this.py", "def omitted_environment_function():\n    pass\n")
	langtest.WriteFixture(t, root, "pkg/generated.py", `
"""Generated fixture with a module docstring."""

# Generated by a fixture; do not edit.
def omitted():
    pass
`)

	first, err := langtest.Analyze(root, analyzer.Options{}, New())
	if err != nil {
		t.Fatal(err)
	}
	second, err := langtest.Analyze(root, analyzer.Options{}, New())
	if err != nil {
		t.Fatal(err)
	}
	firstJSON, err := json.Marshal(first)
	if err != nil {
		t.Fatal(err)
	}
	secondJSON, err := json.Marshal(second)
	if err != nil {
		t.Fatal(err)
	}
	if string(firstJSON) != string(secondJSON) {
		t.Fatal("analysis is not deterministic")
	}
	if len(first.Nodes) != 15 {
		t.Fatalf("nodes = %d, want 15", len(first.Nodes))
	}
	langtest.FindFunction(t, first, "pkg.a.main")

	langtest.AssertEdge(t, first, "pkg.a.Flow.start", "pkg.a.helper", "call")
	langtest.AssertEdge(t, first, "pkg.a.Flow.start", "pkg.a.Flow.finish", "transition")
	langtest.AssertEdge(t, first, "pkg.a.Flow.start", "pkg.a.Flow.alternate", "transition")
	langtest.AssertEdge(t, first, "pkg.a.Worker.build", "pkg.a.Worker.work", "call")
	langtest.AssertEdge(t, first, "pkg.a.Worker.run", "pkg.a.Worker.work", "call")
	langtest.AssertEdge(t, first, "pkg.a.outer", "pkg.a.outer.nested", "call")
	langtest.AssertEdge(t, first, "pkg.a.outer", "pkg.b.imported", "call")
	langtest.AssertEdge(t, first, "pkg.a.outer", "pkg.b.target", "call")
	langtest.AssertEdge(t, first, "pkg.package_call", "pkg.b.target", "call")
}

func TestModernPythonSyntaxAndTestInclusion(t *testing.T) {
	root := t.TempDir()
	langtest.WriteFixture(t, root, "modern.py", `
def generic[T](value: T) -> T:
    try:
        return value
    except* ValueError:
        raise

async def consume(items):
    return [item async for item in items if item]
`)
	langtest.WriteFixture(t, root, "test_modern.py", "def test_visible():\n    pass\n")

	graph, err := langtest.Analyze(root, analyzer.Options{IncludeTests: true}, New())
	if err != nil {
		t.Fatal(err)
	}
	if len(graph.Nodes) != 3 {
		t.Fatalf("nodes = %d, want 3", len(graph.Nodes))
	}
	langtest.FindFunction(t, graph, "modern.consume")
}

func TestRejectsSyntaxErrors(t *testing.T) {
	root := t.TempDir()
	langtest.WriteFixture(t, root, "broken.py", "def broken(:\n    pass\n")
	_, err := langtest.Analyze(root, analyzer.Options{}, New())
	if err == nil {
		t.Fatal("Analyze accepted malformed Python")
	}
	matched, matchErr := regexp.MatchString(`broken\.py:\d+:\d+:`, err.Error())
	if matchErr != nil {
		t.Fatal(matchErr)
	}
	if !matched {
		t.Fatalf("error lacks path, line, and column: %v", err)
	}
}
